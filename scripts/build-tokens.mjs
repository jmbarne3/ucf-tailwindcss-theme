/**
 * Turns tokens/tokens.json and tokens/elements.json into the theme's generated stylesheets.
 *
 *   src/generated/tokens.css     Every `--ucf-*` primitive and the light roles on :root, and one
 *                                `.ucf-composition-*` class per composition. The names match the
 *                                component library's ucf.css, so the theme works with or without
 *                                it on the page, and the two never disagree.
 *
 * The output is committed: sites install this package from source and don't run the build.
 * `npm test` fails if a generated file is out of date.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import {
	compositions,
	loadElements,
	loadTokens,
	primitives,
	roleNames,
	roleVar,
	root,
	toCss,
} from './lib/tokens.mjs';

const HEADER = '/* Generated by scripts/build-tokens.mjs from tokens/. Do not edit. */\n';
const DEFAULT_COMPOSITION = 'light';

const tokens = loadTokens();
const declarations = ( entries, indent = '\t\t' ) =>
	entries.map( ( [ name, value ] ) => `${ indent }${ name }: ${ value };` ).join( '\n' );

// ── tokens.css ───────────────────────────────────────────────────────────────

export function tokensCss() {
	const names = roleNames( tokens );
	const all = compositions( tokens );
	const light = all.find( ( c ) => c.slug === DEFAULT_COMPOSITION );

	const rolesOf = ( composition ) => [
		...names.map( ( role ) => [ roleVar( role ), toCss( composition.roles[ role ] ) ] ),
		// WHY a role of its own: the ground a component paints when it means "this section's
		// background", the same --ucf-surface the library writes.
		[ '--ucf-surface', toCss( composition.background ) ],
	];

	const rootBlock = [
		...primitives( tokens ).map( ( t ) => [ t.cssVar, t.value ] ),
		...rolesOf( light ),
	];

	const compositionBlocks = all.map(
		( c ) => `\t/* ${ c.name } */
\t.ucf-composition-${ c.slug } {
${ declarations( rolesOf( c ) ) }
\t\tbackground-color: var(--ucf-surface);
\t\tborder-color: var(--ucf-line);
\t\tcolor: ${ toCss( c.text ) };
\t}`
	);

	// WHY @layer base: Tailwind utilities (layer utilities) must beat a composition's
	// background, so `ucf-composition-dark bg-raised` paints the raised color. The library's
	// ucf.css, if a site loads it, sets the same values.
	return `${ HEADER }
@layer base {
\t:root {
${ declarations( rootBlock ) }
\t}

${ compositionBlocks.join( '\n\n' ) }
}
`;
}

// ── theme.css ────────────────────────────────────────────────────────────────
//
// Tailwind's namespaces, pointed at the --ucf-* variables. Two blocks:
//
//   @theme         clears Tailwind's defaults where they would put off-brand values in
//                  reach (its 22-hue palette, rounded corners, its type scale and shadows).
//   @theme inline  maps each namespace to a --ucf-* variable. WHY inline: a utility then
//                  compiles to `var(--ucf-link)` itself, not to `var(--color-link)` set once on
//                  :root, so a role re-pointed by a composition reaches every utility inside it.

/** Each namespace's entries as [Tailwind variable, value]. Filled in below, one per group. */
const THEME = [];

const tokensOf = ( group ) => primitives( tokens ).filter( ( t ) => t.group === group );

// Colors: every primitive, then every role. `bg-gold` is always Bold Gold; `bg-accent` is
// whatever the section's accent is.
THEME.push( {
	clear: [ '--color-*' ],
	entries: [
		...tokensOf( 'color' ).map( ( t ) => [ `--color-${ t.slug }`, `var(${ t.cssVar })` ] ),
		...roleNames( tokens ).map( ( role ) => [ `--color-${ role }`, `var(${ roleVar( role ) })` ] ),
		[ '--color-surface', 'var(--ucf-surface)' ],
	],
} );

// Type. Families keep the library's names (`font-display`, `font-body`, `font-mono`).
// WHY sizes are renamed: the library's `body` and `lead` sizes would collide with the `body`
// and `lead` color roles as `text-body` and `text-lead`. They take Tailwind's familiar
// `text-base` and `text-lg`; the rest keep their names, and headings shorten to `text-h1`.
const TEXT_NAMES = {
	data: 'data',
	small: 'sm',
	'data-lg': 'data-lg',
	body: 'base',
	lead: 'lg',
	'heading-6': 'h6',
	'heading-5': 'h5',
	'heading-4': 'h4',
	'heading-3': 'h3',
	'heading-2': 'h2',
	'heading-1': 'h1',
	'display-1': 'display',
};

// Each size's paired line height. Headings, body and data come from elements.json; small,
// data-lg, lead and display have none there, so these four are the theme's own.
const elements = loadElements();
const lineHeightOf = ( key ) => elements.elements[ key ]?.typography?.lineHeight;
const LINE_HEIGHTS = {
	data: lineHeightOf( 'caption' ),
	small: '1.5',
	'data-lg': '1.5',
	body: elements.root.typography.lineHeight,
	lead: '1.5',
	'heading-6': lineHeightOf( 'h6' ),
	'heading-5': lineHeightOf( 'h5' ),
	'heading-4': lineHeightOf( 'h4' ),
	'heading-3': lineHeightOf( 'h3' ),
	'heading-2': lineHeightOf( 'h2' ),
	'heading-1': lineHeightOf( 'h1' ),
	'display-1': '0.95',
};

THEME.push( {
	clear: [ '--font-*', '--text-*' ],
	defaults: [
		[ '--default-font-family', 'var(--ucf-font-family-body)' ],
		[ '--default-mono-font-family', 'var(--ucf-font-family-mono)' ],
	],
	entries: [
		...tokensOf( 'font-family' ).map( ( t ) => [ `--font-${ t.slug }`, `var(${ t.cssVar })` ] ),
		...tokensOf( 'font-size' ).flatMap( ( t ) => {
			const name = TEXT_NAMES[ t.slug ];
			if ( ! name ) {
				throw new Error( `build-tokens: font-size.${ t.slug } has no Tailwind name in TEXT_NAMES.` );
			}
			return [
				[ `--text-${ name }`, `var(${ t.cssVar })` ],
				[ `--text-${ name }--line-height`, LINE_HEIGHTS[ t.slug ] ],
			];
		} ),
		[ '--tracking-heading', elements.elements.heading.typography.letterSpacing ],
		[ '--tracking-button', 'var(--ucf-custom-button-letter-spacing)' ],
		[ '--leading-heading', elements.elements.heading.typography.lineHeight ],
		[ '--leading-body', elements.root.typography.lineHeight ],
	],
} );

export function themeCss() {
	const clear = THEME.flatMap( ( n ) => n.clear ?? [] );
	const defaults = THEME.flatMap( ( n ) => n.defaults ?? [] );
	const entries = THEME.flatMap( ( n ) => n.entries ?? [] );
	const indent = '\t';
	return `${ HEADER }
@theme {
${ declarations( [ ...clear.map( ( name ) => [ name, 'initial' ] ), ...defaults ], indent ) }
}

@theme inline {
${ declarations( entries, indent ) }
}
`;
}

// ── Write ────────────────────────────────────────────────────────────────────

export const OUTPUTS = {
	'src/generated/tokens.css': tokensCss,
	'src/generated/theme.css': themeCss,
};

if ( import.meta.url === `file://${ process.argv[ 1 ] }` ) {
	mkdirSync( path.join( root, 'src/generated' ), { recursive: true } );
	for ( const [ file, build ] of Object.entries( OUTPUTS ) ) {
		writeFileSync( path.join( root, file ), build() );
		console.log( `Wrote ${ file }` );
	}
}
